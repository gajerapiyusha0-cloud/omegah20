def slugify(name: str) -> str:
    return (
        name.lower()
        .replace("&", "and")
        .replace("/", "-")
        .replace(" ", "-")
        .replace("'", "")
    )


def build_domain_catalog() -> list[dict]:
    catalog: list[dict] = []
    index = 0
    for category, color, names in _BASE:
        for name in names:
            phi = (index * 137.508) % 360
            theta = ((index * 23.7) % 160) - 80
            catalog.append(
                {
                    "slug": slugify(name),
                    "name": name,
                    "category": category,
                    "color": color,
                    "orbit": round(phi, 3),
                    "inclination": round(theta, 3),
                    "tags": [category.split()[0].lower(), slugify(name).split("-")[0]],
                    "summary": (
                        f"{name} is a first-class knowledge domain in Virtual GeoTwinVerse. "
                        f"Explore concepts, simulations, spatial links, and cross-disciplinary "
                        f"pathways within {category}."
                    ),
                    "lesson_count": 4 + (index % 8),
                }
            )
            index += 1
    return catalog


DOMAIN_CATALOG = build_domain_catalog()
